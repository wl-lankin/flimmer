export type Key = keyof typeof de;
export const lang: 'de' | 'en' = (navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
const dict = lang === 'de' ? de : en;

export function t(key: Key): string {
  return dict[key];
}

const names: Record<string, string> = lang === 'de'
  ? { ger: 'Deutsch', deu: 'Deutsch', de: 'Deutsch', eng: 'Englisch', en: 'Englisch', fre: 'Französisch', fra: 'Französisch', fr: 'Französisch', spa: 'Spanisch', es: 'Spanisch', ita: 'Italienisch', it: 'Italienisch', jpn: 'Japanisch', ja: 'Japanisch', und: '' }
  : { ger: 'German', deu: 'German', de: 'German', eng: 'English', en: 'English', fre: 'French', fra: 'French', fr: 'French', spa: 'Spanish', es: 'Spanish', ita: 'Italian', it: 'Italian', jpn: 'Japanese', ja: 'Japanese', und: '' };

/** "ger" -> "Deutsch"; unknown codes stay as they are, upper-cased. */
export function language(code?: string): string {
  if (!code) return '';
  return names[code.toLowerCase()] ?? code.toUpperCase();
}
